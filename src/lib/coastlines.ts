/**
 * Coastlines of the world and the land mask built from them.
 *
 * Every shape is a closed ring of [longitude, latitude] points in degrees, traced
 * to a few degrees of accuracy. That is finer than one character cell of the globe,
 * so the continents keep their shape at any rotation.
 *
 * The mask is drawn in three passes: continents, then inland seas cut out of them,
 * then islands on top. Each pass is a plain fill, so no ring needs a hole and rings
 * may overlap freely.
 */

